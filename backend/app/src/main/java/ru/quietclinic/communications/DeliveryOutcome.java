package ru.quietclinic.communications;

/** Итог одной попытки доставки. */
enum DeliveryOutcome {
  /** Получатель принял сообщение. */
  SENT,
  /** Канал не настроен: сообщение остаётся PENDING и ждёт настройки. */
  NOT_CONFIGURED,
  /** Временная ошибка (сеть, 5xx): повтор с паузой. */
  RETRY,
  /** Получатель отказал окончательно (4xx): повтор не поможет. */
  REJECTED
}
